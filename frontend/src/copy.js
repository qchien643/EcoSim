export function errorMessage(error) {
  if (error.fields?.length) return "Dữ liệu đang nhập được giữ nguyên. Bổ sung các mục dưới đây rồi thử lại.";
  if (error.status === 409) return "Bản đang nhập được giữ nguyên. Dữ liệu đã thay đổi hoặc thao tác đang bận; hãy kiểm tra trạng thái trước khi thử lại.";
  if (error.status === 404) return "Không tìm thấy dữ liệu này. Quay lại danh sách để chọn lại.";
  if (error.status >= 500) return "Máy chủ đang gặp sự cố. Dữ liệu đang nhập chưa bị xóa; vui lòng thử lại sau.";
  if (error.status) return "Yêu cầu chưa được chấp nhận. Kiểm tra thông tin hoặc xem chi tiết kỹ thuật.";
  return error.message || "Không thể hoàn tất thao tác. Vui lòng thử lại.";
}
